import { describe, expect, it } from "vitest";

import { counted, plural } from "./plural";

describe("русские числительные", () => {
  it("склоняет по последней цифре", () => {
    expect(plural(1, "скилл", "скилла", "скиллов")).toBe("скилл");
    expect(plural(2, "скилл", "скилла", "скиллов")).toBe("скилла");
    expect(plural(4, "скилл", "скилла", "скиллов")).toBe("скилла");
    expect(plural(5, "скилл", "скилла", "скиллов")).toBe("скиллов");
    expect(plural(0, "скилл", "скилла", "скиллов")).toBe("скиллов");
  });

  it("держит исключение для 11–14", () => {
    for (const n of [11, 12, 13, 14]) {
      expect(plural(n, "запись", "записи", "записей")).toBe("записей");
    }
    expect(plural(21, "запись", "записи", "записей")).toBe("запись");
    expect(plural(22, "запись", "записи", "записей")).toBe("записи");
    expect(plural(111, "запись", "записи", "записей")).toBe("записей");
  });

  it("собирает число со словом", () => {
    expect(counted(1, "изменение", "изменения", "изменений")).toBe(
      "1 изменение",
    );
    expect(counted(3, "изменение", "изменения", "изменений")).toBe(
      "3 изменения",
    );
    expect(counted(7, "изменение", "изменения", "изменений")).toBe(
      "7 изменений",
    );
  });
});
